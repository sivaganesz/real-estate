test('executives: limited hub, no bulk import or history, a pasted document becomes their own draft', async ({ page, consoleProblems }) => {
  test.setTimeout(120_000)
  await page.goto('/today')
  for (const ex of ['profile-u-arjun', 'profile-u-sneha', 'profile-u-vikram'] as const) {
    await switchTo(page, ex)
    await page.getByTestId('sidebar').getByTestId('nav-import').click()
    await expect(page.getByTestId('hub-limited')).toBeVisible()
    await expect(page.getByTestId('no-access')).toHaveCount(0)
    await expect(page.getByTestId('template-cards')).toHaveCount(0)
    for (const url of ['/import/leads', '/import/apartments', '/import/history']) {
      await page.goto(url)
      await expect(page.getByTestId('no-access')).toBeVisible()
    }
  }
  // Vikram reads a pasted enquiry and keeps it as a draft
  await page.goto('/import/document')
  await page.getByRole('button', { name: 'Paste text' }).click()
  await page.locator('#doc-paste').fill('Suresh Kumar 98840 11223 wants a 2 BHK in Velachery, Chennai, budget 80 L, from MagicBricks')
  await page.getByTestId('document-flow').getByRole('button', { name: /Extract|Read/ }).last().click()
  await expect(page.getByTestId('doc-save-draft')).toBeVisible({ timeout: 20_000 })
  const before = await readDb(page)
  await page.getByTestId('doc-save-draft').click()
  await expect(page.getByTestId('doc-done')).toBeVisible()
  const after = await readDb(page)
  const draft = after.drafts.find((d) => !before.drafts.some((b) => b.id === d.id))!
  expect(draft.createdBy).toBe('u-vikram')
  expect(draft.kind).toBe('lead')
  await page.goto('/import/drafts')
  await expect(page.getByTestId(`draft-${draft.id}`)).toBeVisible()
  // executives only see their own drafts
  const others = after.drafts.filter((d) => d.createdBy !== 'u-vikram' && d.status === 'open')
  for (const d of others) await expect(page.getByTestId(`draft-${d.id}`)).toHaveCount(0)
  expect(consoleProblems).toEqual([])
})
