/**
 * M5 Import & Extraction journeys (foundation-plan §8.3 M5, master prompt §15), driven through the real UI and the real
 * profile switcher. Each test starts from a fresh seed (fixtures.ts) and asserts that the change reached the persisted
 * store, not only the screen, and that the console stayed clean. Sample files come from public/samples
 * (scripts/make-samples.mjs). OCR (tesseract.js) needs its CDN on first use, so the image sample is not part of this
 * journey; the text PDF (pdf.js) and pasted text cover document extraction offline.
 */
import type { Page } from '@playwright/test'
import { expect, test } from './fixtures.ts'

type Lead = { id: string; name: string; ownerId: string | null; importJobId?: string; phone: string }
type Property = { id: string; title: string; importJobId?: string }
type Job = { id: string; kind: string; fileName: string; createdBy: string; createdIds: string[]; draftIds: string[] }
type Draft = { id: string; kind: string; status: string; createdBy: string; savedAs?: { id: string } }
type Db = { leads: Lead[]; properties: Property[]; importJobs: Job[]; drafts: Draft[]; settings: { mappingProfiles: { name: string; kind: string }[] } }

const readDb = (page: Page) => page.evaluate(() => (JSON.parse(localStorage.getItem('crm-e2e-db') ?? 'null') as { state: { db: Db } }).state.db)
/** Raw i18next keys that leaked to the screen ("21 columns.xlsx" on a template card is text, not a key). */
const LEAKED_KEY = /\b(import|common|ui|shell|catalogue):[a-zA-Z]|\b(hub|kpi|check|columns|doc|drafts|draft|done|history|samples|template|issue|wizard|upload)\.(?!xlsx|csv)[a-z][A-Za-z]+\b/

async function switchTo(page: Page, testId: string) {
  await page.getByTestId('profile-switcher').click()
  const picker = page.getByTestId('profile-picker')
  await expect(picker).toBeVisible()
  if (testId.startsWith('profile-') && !(await picker.getByTestId(testId).isVisible())) await picker.getByTestId('role-executive').click()
  await picker.getByTestId(testId).click()
  await expect(page.getByTestId('profile-picker')).toBeHidden()
}

async function confirmImport(page: Page) {
  await page.getByTestId('import-confirm').click()
  await page.getByRole('alertdialog').getByRole('button').last().click()
  await expect(page.getByTestId('done-step')).toBeVisible()
}

test('admin: hub, generated templates, lead CSV with mapping, inline fix, import, auto-assign and undo', async ({ page, consoleProblems }) => {
  test.setTimeout(120_000)
  await page.goto('/today')
  await switchTo(page, 'role-admin')
  await page.getByTestId('sidebar').getByTestId('nav-import').click()
  await expect(page.getByTestId('import-hub')).toBeVisible()
  await expect(page.getByTestId('template-cards').locator('article')).toHaveCount(5)
  await expect(page.locator('main')).not.toContainText(LEAKED_KEY)

  // templates are generated by SheetJS on click, in both formats
  for (const [id, file] of [['download-apartments-xlsx', 'apartments-template.xlsx'], ['download-leads-csv', 'leads-template.csv']] as const) {
    const dl = page.waitForEvent('download')
    await page.getByTestId(id).click()
    expect((await dl).suggestedFilename()).toBe(file)
  }

  const before = await readDb(page)
  await page.getByTestId('try-leads99acresExport').click()
  await expect(page.getByTestId('to-check')).toBeVisible({ timeout: 20_000 })

  // save the mapping for next time
  await page.getByTestId('save-mapping').click()
  await page.getByRole('dialog').locator('form').getByRole('button').last().click()
  await expect.poll(async () => (await readDb(page)).settings.mappingProfiles.some((m) => m.kind === 'leads' && m.name === 'leads-99acres-export')).toBe(true)

  await page.getByTestId('to-check').click()
  await expect(page.getByTestId('check-step')).toBeVisible()
  await expect(page.getByTestId('row-6')).toHaveAttribute('data-status', 'duplicate') // already in the CRM
  await expect(page.getByTestId('row-9')).toHaveAttribute('data-status', 'duplicate') // repeated in the file
  const row10 = page.getByTestId('row-10')
  await expect(row10).toHaveAttribute('data-status', 'error')

  // inline fix → the row is checked again
  await page.getByTestId('fix-10').click()
  await row10.locator('[data-field="phone"] input').fill('98765 43210')
  await row10.locator('[data-field="email"] input').fill('lakshmi.p@example.com')
  await page.getByTestId('recheck-10').click()
  await expect(row10).toHaveAttribute('data-status', 'ready')
  await page.getByTestId('skip-12').click()

  await confirmImport(page)
  await expect(page.getByTestId('done-imported')).toContainText('9')
  await expect(page.getByTestId('done-owners')).toBeVisible()

  const after = await readDb(page)
  const job = after.importJobs.find((j) => !before.importJobs.some((b) => b.id === j.id))!
  expect(job.kind).toBe('leads')
  const created = after.leads.filter((l) => l.importJobId === job.id)
  expect(created).toHaveLength(9)
  expect(created.find((l) => l.name === 'Lakshmi Prasad')?.phone).toBe('+919876543210')
  expect(created.every((l) => l.ownerId)).toBe(true) // auto-assigned (E16)

  // the rows not imported, as CSV
  const dl = page.waitForEvent('download')
  await page.getByTestId('download-failed').click()
  expect((await dl).suggestedFilename()).toBe('leads-99acres-export-not-imported.csv')

  // undo removes the job and its leads
  await page.getByTestId('done-step').getByRole('button', { name: /Undo/ }).click()
  await expect.poll(async () => (await readDb(page)).leads.length).toBe(before.leads.length)
  expect((await readDb(page)).importJobs.some((j) => j.id === job.id)).toBe(false)
  expect(consoleProblems).toEqual([])
})

test('admin: messy builder xlsx — tabs and title / totals rows skipped, custom columns mapped, properties created', async ({ page, consoleProblems }) => {
  test.setTimeout(90_000)
  await page.goto('/today')
  await switchTo(page, 'role-admin')
  await page.goto('/import/apartments?sample=builder-price-list-custom.xlsx')
  await expect(page.getByTestId('to-check')).toBeVisible({ timeout: 20_000 })
  const wizard = page.getByTestId('sheet-wizard')
  await expect(wizard).toContainText('"Instructions" tab ignored')
  await expect(wizard).toContainText('totals row skipped')
  await expect(wizard).toContainText('Super built-up area')
  await page.getByTestId('to-check').click()
  // "Call" as the price needs fixing; fix it inline
  const callRow = page.locator('li[data-status="error"]').first()
  await expect(callRow).toContainText('Call')
  const n = (await callRow.getAttribute('data-testid'))!.split('-')[1]
  await page.getByTestId(`fix-${n}`).click()
  await callRow.locator('[data-field="price"] input').fill('1.45 Cr')
  await page.getByTestId(`recheck-${n}`).click()
  await expect(page.getByTestId(`row-${n}`)).not.toHaveAttribute('data-status', 'error')

  const before = await readDb(page)
  await confirmImport(page)
  const after = await readDb(page)
  const job = after.importJobs.find((j) => !before.importJobs.some((b) => b.id === j.id))!
  expect(job.createdIds.length).toBeGreaterThanOrEqual(7)
  expect(after.properties.filter((p) => p.importJobId === job.id).length).toBe(job.createdIds.length)
  expect(job.draftIds.length).toBeGreaterThanOrEqual(1)
  expect(consoleProblems).toEqual([])
})

test('document: brochure PDF → one entry per unit → drafts → finish a draft into a property', async ({ page, consoleProblems }) => {
  test.setTimeout(90_000)
  await page.goto('/today')
  await switchTo(page, 'role-admin')
  await page.goto('/import')
  await page.getByTestId('try-apartmentBrochure').click()
  await expect(page.getByTestId('doc-save-draft')).toBeVisible({ timeout: 30_000 })
  await expect(page.getByTestId('doc-text')).toHaveValue(/Prestige Lakeside Habitat/)
  await expect(page.getByTestId('document-flow')).toContainText('Demo AI')
  const before = await readDb(page)
  await page.getByTestId('doc-save-draft').click()
  await expect(page.getByTestId('doc-done')).toBeVisible()
  const job = (await readDb(page)).importJobs.find((j) => !before.importJobs.some((b) => b.id === j.id))!
  expect(job.draftIds).toHaveLength(2)

  await page.goto('/import/drafts')
  await page.getByTestId(`draft-open-${job.draftIds[0]}`).click()
  await expect(page.getByTestId('draft-page')).toBeVisible()
  await expect(page.locator('[data-low]').first()).toBeVisible() // low-confidence field highlighted
  await page.getByTestId('draft-save').click()
  await expect(page).toHaveURL(/\/properties\//)
  const saved = (await readDb(page)).drafts.find((d) => d.id === job.draftIds[0])!
  expect(saved.status).toBe('saved')
  expect((await readDb(page)).properties.some((p) => p.id === saved.savedAs?.id)).toBe(true)
  expect(consoleProblems).toEqual([])
})

test('history: open a job, remove it with confirm, then undo', async ({ page, consoleProblems }) => {
  await page.goto('/today')
  await switchTo(page, 'role-admin')
  await page.goto('/import/history')
  await page.getByText('99acres-leads.csv').first().click()
  await expect(page.getByTestId('job-drawer')).toBeVisible()
  const count = (await readDb(page)).importJobs.length
  await page.getByTestId('remove-job').click()
  await page.getByRole('alertdialog').getByRole('button').last().click()
  await expect.poll(async () => (await readDb(page)).importJobs.length).toBe(count - 1)
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect.poll(async () => (await readDb(page)).importJobs.length).toBe(count)
  expect(consoleProblems).toEqual([])
})

